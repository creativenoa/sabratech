  for select using (public.is_admin());

drop policy if exists contact_update_admin on public.contact_inquiries;
create policy contact_update_admin on public.contact_inquiries
  for update using (public.is_admin()) with check (public.is_admin());

grant insert on public.contact_inquiries to anon, authenticated;
grant select, update on public.contact_inquiries to authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;


-- ============================================================================
-- PART 3 — FIRST / LAST NAME ON TALENTS  (Pass B)
-- `name` stays the canonical display column for BOTH types and is kept in sync
-- by a trigger for individuals. Startup rows are never touched.
-- ============================================================================

alter table public.talents add column if not exists first_name text default '';
alter table public.talents add column if not exists last_name  text default '';

-- Backfill individuals, splitting on the FIRST space.
-- Guarded so re-running never clobbers values you fixed by hand.
update public.talents
set first_name = btrim(split_part(btrim(name), ' ', 1)),
    last_name  = coalesce(
      nullif(
        btrim(substr(btrim(name), position(' ' in btrim(name)) + 1)),
        btrim(name)
      ), '')
where type = 'individual'
  and coalesce(name, '') <> ''
  and coalesce(first_name, '') = ''
  and coalesce(last_name,  '') = '';

-- Keep `name` in sync from first+last for individuals only.
-- If both parts are blank we leave `name` alone, so a half-typed admin form
-- can never violate the NOT NULL constraint.
create or replace function public.talents_sync_name()
returns trigger
language plpgsql
as $$
declare
  composed text;
begin
  if new.type = 'individual' then
    composed := btrim(concat_ws(' ',
      nullif(btrim(coalesce(new.first_name, '')), ''),
      nullif(btrim(coalesce(new.last_name,  '')), '')
    ));
    if composed <> '' then
      new.name := composed;
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists talents_sync_name_trg on public.talents;
create trigger talents_sync_name_trg
  before insert or update on public.talents
  for each row execute function public.talents_sync_name();

create index if not exists talents_last_name_idx on public.talents (last_name);


