-- ============================================================================
-- PART 1 — ADMIN ALLOWLIST + PROMOTE
-- Why you are stuck: admin_allowlist was never created, and the signup trigger
-- hard-codes status='pending'. So your account has been sitting unapproved.
-- ============================================================================

create table if not exists public.admin_allowlist (
  email      text primary key,
  created_at timestamptz default now()
);
alter table public.admin_allowlist enable row level security;

drop policy if exists allowlist_admin_all on public.admin_allowlist;
create policy allowlist_admin_all on public.admin_allowlist
  for all using (public.is_admin()) with check (public.is_admin());

insert into public.admin_allowlist (email)
values ('noabet@gmail.com'), ('noa@creativenoa.com')
on conflict (email) do nothing;

-- Create a profile row for any allowlisted user who signed up before
-- sabratech-auth.sql existed (no row at all looks identical to "pending").
insert into public.profiles (id, email, full_name, status)
select u.id,
       u.email,
       nullif(coalesce(u.raw_user_meta_data->>'fullName',
                       u.raw_user_meta_data->>'full_name', ''), ''),
       'pending'
from auth.users u
where lower(u.email) in (select lower(email) from public.admin_allowlist)
on conflict (id) do nothing;

-- Keep profiles.email in step with the auth record.
update public.profiles p
set email = u.email
from auth.users u
where p.id = u.id
  and p.email is distinct from u.email;

-- Promote. protect_profile_fields() does not block this: auth.uid() is null
-- inside the SQL editor, so the guard does not fire.
update public.profiles p
set status = 'approved', is_admin = true
from auth.users u
where p.id = u.id
  and lower(u.email) in (select lower(email) from public.admin_allowlist)
  and (p.status is distinct from 'approved' or p.is_admin is distinct from true);

-- Make FUTURE signups from an allowlisted email auto-approve as admin.
-- Replaces the old handle_new_user() which hard-coded 'pending'.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  allowed boolean;
begin
  select exists(
    select 1 from public.admin_allowlist a
    where lower(a.email) = lower(new.email)
  ) into allowed;

  insert into public.profiles (id, email, full_name, status, is_admin)
  values (
    new.id,
    new.email,
    nullif(coalesce(new.raw_user_meta_data->>'fullName',
                    new.raw_user_meta_data->>'full_name', ''), ''),
    case when allowed then 'approved' else 'pending' end,
    allowed
  )
  on conflict (id) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();


