create table if not exists public.contact_inquiries (
  id         bigint generated by default as identity primary key,
  first_name text not null,
  last_name  text not null,
  email      text,
  phone      text,
  message    text not null,
  status     text not null default 'new',
  created_at timestamptz not null default now()
);

create index if not exists contact_inquiries_created_idx
  on public.contact_inquiries (created_at desc);

alter table public.contact_inquiries enable row level security;

-- Anyone (including logged-out visitors) may submit.
drop policy if exists contact_insert_anyone on public.contact_inquiries;
create policy contact_insert_anyone on public.contact_inquiries
  for insert with check (true);

-- Only admins may read or change them.
drop policy if exists contact_select_admin on public.contact_inquiries;
